#!/usr/bin/env python3
"""Universal YASARA distance-measurement mini app (wxPython).

Asks for residue number, receptor atom name, ligand atom (name or element),
and a *_rescored.sce file. Counts poses (base_N.yob files) to get 'lastpose',
writes a YASARA macro modelled on distance_D3-32.mcr, and runs yasara -txt.
"""
import glob
import os
import re
import subprocess
import threading

import wx

MACRO_TEMPLATE = """\
# YASARA MACRO
# TOPIC:       Docking
# TITLE:       Distance between receptor residue {res} atom {atom} and ligand {ligsel} {lig} for each docking pose
# REQUIRES:    Dynamics
# AUTHOR:      generated by yasara_distance_app.py
# LICENSE:     GPL

MacroTarget = '{target}'

# Forcefield to use
ForceField AMBER03,SetPar=Yes

# First and last pose to be analysed
firstpose=1
lastpose={lastpose}

# No change required below this point
# ===================================
OnError Exit
if MacroTarget==''
  RaiseError "This macro requires a target. Either edit the macro file or click Options > Macro > Set target"
else
  LoadSce (MacroTarget)

# Create a table with 2 columns: Pose, Distance
MakeTab Final,Dimensions=2,Columns=2

i=000+firstpose
last=000+lastpose
while i<=last
  DelAll
  # Load next pose
  LoadYob (MacroTarget)_(i)
  ShowMessage 'Analyzing pose (0+i)'
  Tabulate (0+i)|
  Wait 1
  # Check that required atoms exist
  nres = CountAtom Atom {atom} Res {res} Mol A
  nlig = CountAtom {ligsel} {lig} Mol L
  if nres!=1 or nlig<1
    Tabulate -1
  else
    # Distance between receptor {res} {atom} and ligand {ligsel} {lig}
    dist = Distance Atom {atom} Res {res} Mol A,{ligsel} {lig} Mol L
    Tabulate (dist)
  # Next pose
  i=i+1

# Save table, we got 2 columns
header='#____Pose| {atom}-{lig}_Dist'
SaveTab Final,{table},Format=Text,Columns=2,NumFormat=9.2f,(header)

# Exit YASARA if this macro was provided as command line argument in console mode
if runWithMacro and ConsoleMode
  Exit
"""


def build_macro(target, res, atom, lig, ligsel, lastpose):
    table = "%s_distances" % target
    return MACRO_TEMPLATE.format(target=target, res=res, atom=atom, lig=lig,
                                 ligsel=ligsel, lastpose=lastpose, table=table)


class MainFrame(wx.Frame):
    def __init__(self):
        super().__init__(None, title="YASARA distance macro runner",
                         size=(560, 460))
        panel = wx.Panel(self)
        s = wx.FlexGridSizer(rows=0, cols=2, vgap=8, hgap=8)
        s.AddGrowableCol(1, 1)

        s.Add(wx.StaticText(panel, label="Residue number:"), 0,
              wx.ALIGN_CENTER_VERTICAL)
        self.res = wx.TextCtrl(panel, value="105")
        s.Add(self.res, 1, wx.EXPAND)

        s.Add(wx.StaticText(panel, label="Receptor atom name:"), 0,
              wx.ALIGN_CENTER_VERTICAL)
        self.atom = wx.TextCtrl(panel, value="OD2")
        s.Add(self.atom, 1, wx.EXPAND)

        s.Add(wx.StaticText(panel, label="Ligand atom name:"), 0,
              wx.ALIGN_CENTER_VERTICAL)
        self.lig = wx.TextCtrl(panel, value="N")
        s.Add(self.lig, 1, wx.EXPAND)

        s.Add(wx.StaticText(panel, label="Ligand selector:"), 0,
              wx.ALIGN_CENTER_VERTICAL)
        self.ligsel = wx.ComboBox(panel, choices=["Element", "Atom"],
                                  value="Element",
                                  style=wx.CB_READONLY)
        s.Add(self.ligsel, 1, wx.EXPAND)

        s.Add(wx.StaticText(panel, label="MacroTarget (.sce):"), 0,
              wx.ALIGN_CENTER_VERTICAL)
        row = wx.BoxSizer(wx.HORIZONTAL)
        self.sce = wx.TextCtrl(panel)
        btn = wx.Button(panel, label="Browse...")
        btn.Bind(wx.EVT_BUTTON, self.on_browse)
        row.Add(self.sce, 1, wx.EXPAND | wx.RIGHT, 4)
        row.Add(btn, 0)
        s.Add(row, 1, wx.EXPAND)

        self.run = wx.Button(panel, label="Write macro and run yasara -txt")
        self.run.Bind(wx.EVT_BUTTON, self.on_run)
        self.log = wx.TextCtrl(panel, style=wx.TE_MULTILINE | wx.TE_READONLY)

        outer = wx.BoxSizer(wx.VERTICAL)
        outer.Add(s, 0, wx.ALL | wx.EXPAND, 10)
        outer.Add(self.run, 0, wx.LEFT | wx.RIGHT | wx.BOTTOM | wx.EXPAND, 10)
        outer.Add(self.log, 1, wx.LEFT | wx.RIGHT | wx.BOTTOM | wx.EXPAND, 10)
        panel.SetSizer(outer)

    def on_browse(self, _evt):
        with wx.FileDialog(self, "Select *_rescored.sce",
                           wildcard="SCE files (*_rescored.sce)|*_rescored.sce|All SCE files (*.sce)|*.sce",
                           style=wx.FD_OPEN | wx.FD_FILE_MUST_EXIST) as dlg:
            if dlg.ShowModal() == wx.ID_OK:
                self.sce.SetValue(dlg.GetPath())

    def count_poses(self, directory, base):
        nums = []
        for p in glob.glob(os.path.join(directory, base + "_*.yob")):
            m = re.search(r"_(\d+)\.yob$", p)
            if m:
                nums.append(int(m.group(1)))
        return (max(nums), len(nums)) if nums else (0, 0)

    def on_run(self, _evt):
        sce = self.sce.GetValue().strip()
        res = self.res.GetValue().strip()
        atom = self.atom.GetValue().strip()
        lig = self.lig.GetValue().strip()
        ligsel = self.ligsel.GetValue()
        if not sce or not os.path.isfile(sce):
            wx.MessageBox("Please select an existing *_rescored.sce file.",
                          "Error", wx.ICON_ERROR)
            return
        if not res.isdigit():
            wx.MessageBox("Residue number must be an integer.",
                          "Error", wx.ICON_ERROR)
            return
        if not atom or not lig:
            wx.MessageBox("Atom names must not be empty.",
                          "Error", wx.ICON_ERROR)
            return

        directory = os.path.dirname(os.path.abspath(sce))
        base = os.path.splitext(os.path.basename(sce))[0]
        lastpose, nfiles = self.count_poses(directory, base)
        if lastpose == 0:
            wx.MessageBox("No pose files %s_<n>.yob found in %s"
                          % (base, directory), "Error", wx.ICON_ERROR)
            return

        macro = build_macro(base, res, atom, lig, ligsel, lastpose)
        mcr_path = os.path.join(
            directory, "distance_%s%s-%s.mcr" % (res, atom, lig))
        with open(mcr_path, "w") as fh:
            fh.write(macro)
        self.log.AppendText(
            "Wrote %s (poses found: %d, lastpose=%d)\n"
            % (mcr_path, nfiles, lastpose))

        self.run.Disable()
        threading.Thread(target=self._run_yasara,
                         args=(mcr_path,), daemon=True).start()

    def _run_yasara(self, mcr_path):
        wx.CallAfter(self.log.AppendText, "Running: yasara -txt %s\n" % mcr_path)
        try:
            proc = subprocess.run(["yasara", "-txt", mcr_path],
                                  capture_output=True, text=True)
            out = (proc.stdout or "") + (proc.stderr or "")
            tail = "\n".join(out.splitlines()[-20:])
            wx.CallAfter(self.log.AppendText,
                         "Exit code %d\n%s\n" % (proc.returncode, tail))
        except OSError as exc:
            wx.CallAfter(self.log.AppendText, "Failed to start yasara: %s\n" % exc)
        finally:
            wx.CallAfter(self.run.Enable)


if __name__ == "__main__":
    app = wx.App()
    MainFrame().Show()
    app.MainLoop()
